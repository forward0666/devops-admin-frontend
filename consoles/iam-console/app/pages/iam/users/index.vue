            <!-- Group list -->
            <div v-if="createForm.permissionMode === 'group'" class="max-h-60 overflow-y-auto border border-gray-200 rounded-md divide-y divide-gray-100">
              <label v-for="g in filteredGroups" :key="g.id" class="flex items-center gap-3 px-4 py-2.5 hover:bg-blue-50/50 cursor-pointer">
                <input type="checkbox" :value="g.name" v-model="createForm.groups" class="text-blue-600 rounded" />
                <div>
                  <span class="text-sm font-medium text-gray-900">{{ g.name }}</span>
                  <span class="text-xs text-gray-500 ml-2">{{ g.description }}</span>
                </div>
              </label>
              <p v-if="!filteredGroups.length" class="px-4 py-6 text-sm text-gray-400 text-center">No groups found</p>
            </div>

            <!-- Copy from user -->
            <div v-if="createForm.permissionMode === 'copy'" class="space-y-3">
              <p class="text-sm text-gray-600">Select a user to copy permissions from:</p>
              <select v-model="createForm.copyFromUser" class="w-full max-w-md px-3 py-2 border border-gray-300 rounded-md text-sm focus:outline-none focus:ring-2 focus:ring-blue-500">
                <option value="">Select a user...</option>
