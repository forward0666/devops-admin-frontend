<script setup lang="ts">
const router = useRouter()
const page = ref(1)
const pageSize = 20
const search = ref('')
const { data, refresh } = await useFetch('/api/iam/users-full', {
  query: computed(() => ({ page: page.value, pageSize, search: search.value }))
})

// Column visibility
const showColumnSelector = ref(false)
const columns = ref([
  { key: 'username', label: 'User name', visible: true, required: true },
  { key: 'groups', label: 'Groups', visible: true },
  { key: 'accessKeyAge', label: 'Access key age', visible: true },
  { key: 'passwordAge', label: 'Password age', visible: true },
  { key: 'mfa', label: 'MFA', visible: true },
  { key: 'lastActivity', label: 'Last activity', visible: true },
  { key: 'consoleLastSignIn', label: 'Console last sign-in', visible: true },
  { key: 'accessKeyLastUsed', label: 'Access key last used', visible: true },
])
const visibleColumns = computed(() => columns.value.filter(c => c.visible))

// Create user wizard state
const showCreateWizard = ref(false)
const createStep = ref(1)
const createSuccess = ref(false)
const createdUsername = ref('')
const createdUserId = ref('')
const createForm = ref({
  username: '',
  consoleAccess: false,
  passwordType: 'autogenerated' as 'autogenerated' | 'custom',
  customPassword: '',
  requirePasswordChange: true,
  permissionMode: 'group' as 'group' | 'copy' | 'direct',
  groups: [] as string[],
  copyFromUser: '',
  policies: [] as string[],
  tags: [{ key: '', value: '' }] as { key: string; value: string }[]
})
const creating = ref(false)
const permissionSearch = ref('')
const policyTypeFilter = ref('all')

// Fetch groups and policies for wizard
const { data: groupsData } = await useFetch('/api/iam/groups-full', { query: { pageSize: 100 } })
const { data: policiesData } = await useFetch('/api/iam/policies-full', { query: { pageSize: 100 } })

const filteredGroups = computed(() => {
  const items = groupsData.value?.items || []
  if (!permissionSearch.value) return items
  return items.filter((g: any) => g.name.toLowerCase().includes(permissionSearch.value.toLowerCase()))
})

const filteredPolicies = computed(() => {
  let items = policiesData.value?.items || []
  if (policyTypeFilter.value !== 'all') {
    items = items.filter((p: any) => policyTypeFilter.value === 'managed' ? p.type === 'Managed' : p.type === 'Custom')
  }
  if (!permissionSearch.value) return items
  return items.filter((p: any) => p.name.toLowerCase().includes(permissionSearch.value.toLowerCase()))
})

// Delete confirmation
const showDeleteConfirm = ref(false)
const deleteTarget = ref<{ id: string; username: string } | null>(null)
const deleteConfirmText = ref('')
const deleting = ref(false)

// Edit dialog
const showEditDialog = ref(false)
const editTarget = ref<any>(null)
const editForm = ref({ username: '', email: '' })
const saving = ref(false)

// Actions dropdown
const openActions = ref<string | null>(null)

function openCreateWizard() {
  createForm.value = {
    username: '', consoleAccess: false, passwordType: 'autogenerated', customPassword: '',
    requirePasswordChange: true, permissionMode: 'group', groups: [], copyFromUser: '',
    policies: [], tags: [{ key: '', value: '' }]
  }
  createStep.value = 1
  createSuccess.value = false
  showCreateWizard.value = true
}

function addTag() { createForm.value.tags.push({ key: '', value: '' }) }
function removeTag(i: number) { createForm.value.tags.splice(i, 1) }

function canProceedStep1() {
  if (!createForm.value.username.trim()) return false
  if (createForm.value.consoleAccess && createForm.value.passwordType === 'custom' && !createForm.value.customPassword) return false
  return true
}

async function submitCreate() {
  creating.value = true
  try {
    const res = await $fetch<any>('/api/iam/users-full', {
      method: 'POST',
      body: {
        username: createForm.value.username,
        consoleAccess: createForm.value.consoleAccess,
        passwordType: createForm.value.passwordType,
        groups: createForm.value.groups,
        policies: createForm.value.policies,
        tags: createForm.value.tags.filter(t => t.key)
      }
    })
    createdUsername.value = createForm.value.username
    createdUserId.value = res.id || 'u' + Date.now()
    createSuccess.value = true
  } finally {
    creating.value = false
  }
}

function downloadCsv() {
  const csv = `User Name,Password,Access Key,Console URL\n${createdUsername.value},${createForm.value.consoleAccess ? (createForm.value.passwordType === 'autogenerated' ? 'Auto-generated' : createForm.value.customPassword) : 'N/A'},N/A,https://console.example.com/`
  const blob = new Blob([csv], { type: 'text/csv' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url; a.download = `${createdUsername.value}-credentials.csv`; a.click()
  URL.revokeObjectURL(url)
}

function confirmDelete(user: any) {
  deleteTarget.value = { id: user.id, username: user.username }
  deleteConfirmText.value = ''
  showDeleteConfirm.value = true
  openActions.value = null
}

async function doDelete() {
  if (!deleteTarget.value || deleteConfirmText.value !== deleteTarget.value.username) return
  deleting.value = true
  try {
    await $fetch(`/api/iam/users-full/${deleteTarget.value.id}`, { method: 'DELETE' })
    showDeleteConfirm.value = false
    deleteTarget.value = null
    await refresh()
  } finally { deleting.value = false }
}

function openEdit(user: any) {
  editTarget.value = user
  editForm.value = { username: user.username, email: user.email }
  showEditDialog.value = true
  openActions.value = null
}

async function doEdit() {
  if (!editTarget.value) return
  saving.value = true
  try {
    await $fetch(`/api/iam/users-full/${editTarget.value.id}`, { method: 'PUT', body: editForm.value })
    showEditDialog.value = false
    editTarget.value = null
    await refresh()
  } finally { saving.value = false }
}

function toggleActions(id: string) {
  openActions.value = openActions.value === id ? null : id
}

function relativeTime(dateStr: string) {
  if (!dateStr || dateStr === 'Never') return 'Never'
  const d = new Date(dateStr)
  const now = new Date()
  const diffMs = now.getTime() - d.getTime()
  const days = Math.floor(diffMs / 86400000)
  if (days === 0) return 'Today'
  if (days === 1) return 'Yesterday'
  if (days < 30) return `${days} days ago`
  if (days < 365) return `${Math.floor(days / 30)} months ago`
  return `${Math.floor(days / 365)} years ago`
}

function closeAll() {
  showColumnSelector.value = false
  openActions.value = null
}
</script>

