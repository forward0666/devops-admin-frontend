              <input v-model="permissionSearch" type="text" :placeholder="createForm.permissionMode === 'group' ? 'Search groups...' : 'Search policies...'" class="w-full max-w-sm px-3 py-2 border border-gray-300 rounded-md text-sm focus:outline-none focus:ring-2 focus:ring-blue-500" />
            </div>

            <!-- Policy type filter -->
            <div v-if="createForm.permissionMode === 'direct'" class="flex gap-2 mb-3">
              <button v-for="f in [{ key: 'all', label: 'All' }, { key: 'managed', label: 'Managed' }, { key: 'customer', label: 'Custom' }]" :key="f.key"
                @click="policyTypeFilter = f.key"
                :class="['px-3 py-1 text-xs rounded-full border transition-colors', policyTypeFilter === f.key ? 'bg-blue-600 text-white border-blue-600' : 'bg-white text-gray-600 border-gray-300 hover:bg-gray-50']">
                {{ f.label }}
