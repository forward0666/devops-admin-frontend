                <input type="checkbox" :value="p.name" v-model="createForm.policies" class="text-blue-600 rounded" />
                <div class="flex-1 min-w-0">
                  <span class="text-sm font-medium text-gray-900">{{ p.name }}</span>
                  <div class="flex items-center gap-2 mt-0.5">
                    <span :class="['text-xs px-1.5 py-0.5 rounded', p.type === 'Managed' ? 'bg-blue-100 text-blue-700' : 'bg-gray-100 text-gray-600']">{{ p.type }}</span>
                    <span class="text-xs text-gray-400 truncate">{{ p.description }}</span>
                  </div>
                </div>
              </label>
              <p v-if="!filteredPolicies.length" class="px-4 py-6 text-sm text-gray-400 text-center">No policies found</p>
            </div>
          </div>

          <!-- Step 3: Add tags -->
          <div v-if="createStep === 3" class="p-6">
            <h2 class="text-lg font-bold text-gray-900 mb-1">Add tags</h2>
            <p class="text-sm text-gray-500 mb-6">Step 3 of 4 — Tags are key-value pairs that help you organize and track users (optional)</p>

            <div class="space-y-2">
              <div class="grid grid-cols-[1fr_1fr_40px] gap-2 mb-1">
                <span class="text-xs font-semibold text-gray-500 uppercase">Key</span>
                <span class="text-xs font-semibold text-gray-500 uppercase">Value</span>
                <span></span>
              </div>
              <div v-for="(tag, i) in createForm.tags" :key="i" class="grid grid-cols-[1fr_1fr_40px] gap-2 items-center">
                <input v-model="tag.key" type="text" placeholder="Key" class="px-3 py-2 border border-gray-300 rounded-md text-sm focus:outline-none focus:ring-2 focus:ring-blue-500" />
                <input v-model="tag.value" type="text" placeholder="Value" class="px-3 py-2 border border-gray-300 rounded-md text-sm focus:outline-none focus:ring-2 focus:ring-blue-500" />
                <button @click="removeTag(i)" class="p-2 text-red-500 hover:text-red-700 hover:bg-red-50 rounded">
                  <svg class="w-4 h-4" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M19 7l-.867 12.142A2 2 0 0116.138 21H7.862a2 2 0 01-1.995-1.858L5 7m5 4v6m4-6v6m1-10V4a1 1 0 00-1-1h-4a1 1 0 00-1 1v3M4 7h16" /></svg>
                </button>
              </div>
            </div>
            <button @click="addTag()" class="mt-3 text-sm text-blue-600 hover:text-blue-800 flex items-center gap-1">
              <svg class="w-4 h-4" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M12 4v16m8-8H4" /></svg>
              Add another tag
            </button>
          </div>

          <!-- Step 4: Review -->
          <div v-if="createStep === 4" class="p-6">
            <h2 class="text-lg font-bold text-gray-900 mb-1">Review and create</h2>
            <p class="text-sm text-gray-500 mb-6">Step 4 of 4 — Review the user details before creating</p>

            <div class="space-y-5">
              <!-- User details -->
              <div class="bg-gray-50 rounded-lg p-4">
                <h3 class="text-sm font-semibold text-gray-700 mb-3">User details</h3>
                <dl class="grid grid-cols-[140px_1fr] gap-y-2 text-sm">
                  <dt class="text-gray-500">User name</dt>
                  <dd class="text-gray-900 font-medium">{{ createForm.username }}</dd>
                  <dt class="text-gray-500">Console access</dt>
                  <dd class="text-gray-900">{{ createForm.consoleAccess ? 'Yes' : 'No' }}</dd>
                  <template v-if="createForm.consoleAccess">
                    <dt class="text-gray-500">Password type</dt>
                    <dd class="text-gray-900">{{ createForm.passwordType === 'autogenerated' ? 'Autogenerated' : 'Custom' }}</dd>
                  </template>
                </dl>
              </div>

              <!-- Permissions -->
              <div class="bg-gray-50 rounded-lg p-4">
                <h3 class="text-sm font-semibold text-gray-700 mb-3">Permissions</h3>
                <dl class="grid grid-cols-[140px_1fr] gap-y-2 text-sm">
                  <dt class="text-gray-500">Permission type</dt>
                  <dd class="text-gray-900">{{ { group: 'Group membership', copy: 'Copy from user', direct: 'Direct policies' }[createForm.permissionMode] }}</dd>
                  <template v-if="createForm.permissionMode === 'group'">
                    <dt class="text-gray-500">Groups</dt>
                    <dd class="text-gray-900">{{ createForm.groups.length ? createForm.groups.join(', ') : 'None' }}</dd>
                  </template>
                  <template v-if="createForm.permissionMode === 'copy'">
                    <dt class="text-gray-500">Copy from</dt>
                    <dd class="text-gray-900">{{ createForm.copyFromUser || 'None' }}</dd>
                  </template>
                  <template v-if="createForm.permissionMode === 'direct'">
                    <dt class="text-gray-500">Policies</dt>
                    <dd class="text-gray-900">{{ createForm.policies.length ? createForm.policies.join(', ') : 'None' }}</dd>
                  </template>
                </dl>
              </div>

              <!-- Tags -->
              <div class="bg-gray-50 rounded-lg p-4">
                <h3 class="text-sm font-semibold text-gray-700 mb-3">Tags</h3>
                <div v-if="createForm.tags.filter(t => t.key).length">
                  <div v-for="tag in createForm.tags.filter(t => t.key)" :key="tag.key" class="flex gap-2 text-sm mb-1">
                    <span class="font-medium text-gray-700">{{ tag.key }}:</span>
                    <span class="text-gray-600">{{ tag.value }}</span>
                  </div>
                </div>
                <p v-else class="text-sm text-gray-400">No tags</p>
              </div>
            </div>
          </div>

          <!-- Wizard footer -->
          <div class="px-6 py-4 border-t border-gray-200 flex items-center justify-between">
            <button v-if="createStep > 1" @click="createStep--" class="px-4 py-2 text-sm text-gray-700 bg-white border border-gray-300 rounded-md hover:bg-gray-50">
              Previous
            </button>
            <div v-else />
            <div class="flex gap-2">
              <button @click="showCreateWizard = false" class="px-4 py-2 text-sm text-gray-700 bg-white border border-gray-300 rounded-md hover:bg-gray-50">Cancel</button>
              <button v-if="createStep < 4" @click="createStep++" :disabled="createStep === 1 && !canProceedStep1()" class="px-4 py-2 text-sm text-white bg-blue-600 rounded-md hover:bg-blue-700 disabled:opacity-50 disabled:cursor-not-allowed">
                Next
              </button>
              <button v-else @click="submitCreate()" :disabled="creating" class="px-6 py-2 text-sm text-white bg-blue-600 rounded-md hover:bg-blue-700 disabled:opacity-50">
                {{ creating ? 'Creating...' : 'Create user' }}
              </button>
            </div>
          </div>
        </div>
      </div>
